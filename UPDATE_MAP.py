def load_csv(zf, name):
    with zf.open(name) as f:
        df = pd.read_csv(f, dtype=str, encoding="utf-8-sig", low_memory=False)
    df.columns = [c.strip() for c in df.columns]
    return df

acftref = load_csv(z, "ACFTREF.txt")
master  = load_csv(z, "MASTER.txt")

mooney_ref = acftref[acftref["CODE"].str.startswith("587", na=False)].copy()
mooney_ref["MODEL"] = mooney_ref["MODEL"].str.strip()
code_to_model = dict(zip(mooney_ref["CODE"], mooney_ref["MODEL"]))

master["MFR MDL CODE"] = master["MFR MDL CODE"].str.strip()
mooney = master[master["MFR MDL CODE"].isin(code_to_model)].copy()
mooney["MODEL"] = mooney["MFR MDL CODE"].map(code_to_model)
total_all   = len(mooney)
mooney = mooney[mooney["STATUS CODE"].astype(str).str.strip().eq("V")].copy()
total_valid = len(mooney)
mooney["ModelDisplay"] = mooney["MODEL"].apply(
    lambda m: re.sub(r"[\s\-]+", "", str(m).strip()))

print("          Total Mooney registrations found: {:,}".format(total_all))
print("          Valid (active) registrations:     {:,}".format(total_valid))


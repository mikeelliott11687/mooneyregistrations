def jitter(seed, radius):
    h = 0
    for c in seed:
        h = (h * 31 + ord(c)) & 0xFFFFFFFF
    return ((h % 89) - 44) * (radius / 44), ((h % 67) - 33) * (radius / 33)

def geocode(n, city, state, country):
    cu = city.upper().strip()
    su = state.upper().strip()
    if (cu, su) in CITY_LL:
        lat, lon = CITY_LL[(cu, su)]
        dlat, dlon = jitter(n + cu, 0.018)
        return round(lat + dlat, 5), round(lon + dlon, 5), "city"
    if su in ST_LL:
        lat, lon = ST_LL[su]
        dlat, dlon = jitter(n + su, 0.7)
        return round(lat + dlat, 5), round(lon + dlon, 5), "state"
    if country in CO_LL:
        lat, lon = CO_LL[country]
        dlat, dlon = jitter(n + country, 0.6)
        return round(lat + dlat, 5), round(lon + dlon, 5), "country"
    return None, None, "none"

def hex_color(i):
    hue = (i * 0.618033988) % 1.0
    sat = 0.78 if i % 2 == 0 else 0.62
    r, g, b = colorsys.hsv_to_rgb(hue, sat, 0.85)
    return "#%02x%02x%02x" % (int(r*255), int(g*255), int(b*255))

